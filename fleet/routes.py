def normalize_city(name):
    """Убираем лишние пробелы, учитываем написание с ё/е и разные тире."""
    return " ".join(
        str(name or "")
        .casefold()
        .replace("ё", "е")
        .replace("—", "-")
        .replace("–", "-")
        .split()
    )


_CITY_BY_KEY = {normalize_city(name): name for name in CITY_LOCATIONS}

# Распространённые сокращения и опечатка из реального пользовательского ввода.
_CITY_ALIASES = {
    "спб": "Санкт-Петербург",
    "питер": "Санкт-Петербург",
    "екатиринбург": "Екатеринбург",
    "екб": "Екатеринбург",
    "н. новгород": "Нижний Новгород",
    "нижний": "Нижний Новгород",
    "ростов на дону": "Ростов-на-Дону",
}


def canonical_city(name):
    """Возвращает единое название города или None, если город неизвестен."""
    key = normalize_city(name)
    return _CITY_BY_KEY.get(key) or _CITY_ALIASES.get(key)


def city_choices():
    """Один общий список для HTML-подсказок и проверки на сервере."""
    return sorted(CITY_LOCATIONS, key=str.casefold)


def coordinates_for_city(city):
    canonical = canonical_city(city)
    return CITY_LOCATIONS.get(canonical)


def schematic_route(origin, destination):
    """Учебная прямая между центрами поддерживаемых городов, не дорога."""
    start, finish = coordinates_for_city(origin), coordinates_for_city(destination)
    if start is None or finish is None or start == finish:
        return None
    return [start, finish]
